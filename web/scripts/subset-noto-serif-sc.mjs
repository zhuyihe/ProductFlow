#!/usr/bin/env node
/**
 * Subset Noto Serif SC font to only characters actually used in src/.
 *
 * Strategy:
 *   1) Scan web/src/** for all CJK / CJK Ext A / Kana / fullwidth punctuation chars.
 *   2) Add an ASCII + Latin-1 + common Chinese punctuation safety net (so the font
 *      remains usable as a serif fallback even for chars we missed in static scan).
 *   3) Invoke `pyftsubset` to produce woff2 from the @fontsource source.
 *   4) Write font into web/public/fonts/, plus a small @font-face CSS partial.
 *
 * Run with: node scripts/subset-noto-serif-sc.mjs
 * Requires: Python 3 + fontTools + brotli installed on PATH.
 */

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, mkdirSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WEB_ROOT = resolve(__dirname, "..");
const SRC_DIR = join(WEB_ROOT, "src");
const FONT_SRC_400 = join(
  WEB_ROOT,
  "node_modules",
  "@fontsource",
  "noto-serif-sc",
  "files",
  "noto-serif-sc-chinese-simplified-400-normal.woff2",
);
const OUT_DIR = join(WEB_ROOT, "public", "fonts");
const OUT_FONT = join(OUT_DIR, "noto-serif-sc-subset-400.woff2");

// Ranges allowed as scan targets (Unicode codepoint inclusive ranges).
const CJK_RANGES = [
  [0x3400, 0x4dbf], // CJK Unified Ideographs Extension A
  [0x4e00, 0x9fff], // CJK Unified Ideographs
  [0x3040, 0x309f], // Hiragana
  [0x30a0, 0x30ff], // Katakana
  [0xff00, 0xffef], // Halfwidth and Fullwidth Forms
  [0x3000, 0x303f], // CJK Symbols and Punctuation
  [0x2e80, 0x2eff], // CJK Radicals Supplement
];

const isCJK = (cp) => CJK_RANGES.some(([lo, hi]) => cp >= lo && cp <= hi);

const TEXT_EXTS = new Set([".ts", ".tsx", ".js", ".jsx", ".css", ".html", ".md", ".json"]);

function walk(dir, out = []) {
  for (const entry of readdirSync(dir)) {
    if (entry === "node_modules" || entry.startsWith(".")) continue;
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) walk(full, out);
    else if (TEXT_EXTS.has("." + entry.split(".").pop())) out.push(full);
  }
  return out;
}

function collectChars() {
  const chars = new Set();
  // Always-included safety net: full printable ASCII + Latin-1 supplement.
  for (let cp = 0x20; cp <= 0xff; cp++) chars.add(cp);
  // Common Chinese punctuation explicitly (already covered by CJK_RANGES, but be explicit).
  for (const c of "，。、；：？！“”‘’（）《》〈〉【】「」『』·—…￥") {
    chars.add(c.codePointAt(0));
  }

  const files = walk(SRC_DIR);
  for (const f of files) {
    const text = readFileSync(f, "utf8");
    for (const ch of text) {
      const cp = ch.codePointAt(0);
      if (isCJK(cp)) chars.add(cp);
    }
  }
  return chars;
}

function toUnicodeArgs(chars) {
  // pyftsubset --unicodes accepts comma-separated hex codepoints.
  // Group into ranges for compactness; argv on Windows has length limits.
  const sorted = [...chars].sort((a, b) => a - b);
  const parts = [];
  let runStart = sorted[0];
  let runEnd = sorted[0];
  for (let i = 1; i < sorted.length; i++) {
    if (sorted[i] === runEnd + 1) {
      runEnd = sorted[i];
    } else {
      parts.push(runStart === runEnd ? `U+${runStart.toString(16)}` : `U+${runStart.toString(16)}-${runEnd.toString(16)}`);
      runStart = sorted[i];
      runEnd = sorted[i];
    }
  }
  parts.push(runStart === runEnd ? `U+${runStart.toString(16)}` : `U+${runStart.toString(16)}-${runEnd.toString(16)}`);
  return parts.join(",");
}

function main() {
  if (!existsSync(FONT_SRC_400)) {
    console.error(`[subset] Source font missing: ${FONT_SRC_400}`);
    console.error("[subset] Run `pnpm install` first.");
    process.exit(1);
  }

  console.log("[subset] Scanning src/ for CJK chars...");
  const chars = collectChars();
  const cjkCount = [...chars].filter((cp) => isCJK(cp)).length;
  console.log(`[subset] Found ${chars.size} unique codepoints (${cjkCount} CJK).`);

  mkdirSync(OUT_DIR, { recursive: true });
  const unicodeArg = toUnicodeArgs(chars);

  console.log("[subset] Invoking pyftsubset...");
  execFileSync(
    "python",
    [
      "-m",
      "fontTools.subset",
      FONT_SRC_400,
      `--unicodes=${unicodeArg}`,
      "--flavor=woff2",
      "--layout-features=*",
      "--no-hinting",
      "--desubroutinize",
      `--output-file=${OUT_FONT}`,
    ],
    { stdio: "inherit" },
  );

  const size = statSync(OUT_FONT).size;
  console.log(`[subset] Wrote ${OUT_FONT} (${(size / 1024).toFixed(1)} KB).`);

  // Drop a small CSS fragment alongside for documentation; main.tsx imports the
  // canonical @font-face via index.css instead.
  const cssNote = `/* Generated by scripts/subset-noto-serif-sc.mjs. Source font: @fontsource/noto-serif-sc 400.
 * Unique codepoints: ${chars.size} (${cjkCount} CJK).
 * Subset size: ${(size / 1024).toFixed(1)} KB.
 */\n`;
  writeFileSync(join(OUT_DIR, "noto-serif-sc-subset.README"), cssNote);
}

main();
